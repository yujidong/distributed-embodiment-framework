/**
 * Flow wizard helpers (R14 P1-1; R2-UX-20 更名「引导式造 Flow」) — pure
 * functions behind the FlowsPage
 * guided builder: 「我想让 [区域] 在 [参数 阈值] 时自动
 * [动作]」. The wizard emits exactly ONE canonical flow shape — a
 * zone-scoped `condition` trigger plus a single action node — so the result
 * always passes the server's validateFlow and actually runs (the invoker
 * refuses cross-zone actuation, so the action capability must be deliverable
 * by a device IN the trigger zone — see zoneActionOptions).
 */

import type { CreateFlowInput, EnvZone, WorldAgent, WorldDevice } from '../api/types';

export type WizardOp = '>' | '<' | '>=' | '<=';
export const WIZARD_OPS: readonly WizardOp[] = ['>', '>=', '<', '<='];

/**
 * Parameter vocabulary for zones that declare no numeric baseline — the
 * well-known environment parameters the simulation tracks.
 */
export const FALLBACK_PARAMETERS = [
  'temperature',
  'humidity',
  'co2',
  'smoke',
  'occupancy',
  'light',
  'noise',
] as const;

/**
 * Trigger parameters offerable for a zone: the numeric keys of its baseline
 * when declared, else the fallback vocabulary (identifiers, not copy).
 */
export function zoneParameters(zone: EnvZone | undefined): string[] {
  const numeric = Object.entries(zone?.baseline ?? {})
    .filter(([, value]) => typeof value === 'number')
    .map(([key]) => key)
    .sort((a, b) => a.localeCompare(b));
  return numeric.length > 0 ? numeric : [...FALLBACK_PARAMETERS];
}

export interface ZoneActionOption {
  capability: string;
  /** Names of the in-zone devices providing the capability. */
  deviceNames: string[];
}

/**
 * True when a device capability list provides `capability` — mirrors the
 * flow-invoker's matching: exact name first, then case-insensitive
 * containment either way ('cooling' ↔ 'temperature-control').
 */
export function deviceProvides(
  deviceCapabilities: readonly string[],
  capability: string,
): boolean {
  const needle = capability.toLowerCase();
  return deviceCapabilities.some(
    c => c === capability || c.toLowerCase().includes(needle) || needle.includes(c.toLowerCase()),
  );
}

/**
 * Actions a zone-scoped flow can actually execute in `zoneId`: capabilities
 * provided by a device IN the zone that at least one agent is bound to.
 * Anything weaker is either 422-rejected at creation (no agent can deliver)
 * or fails at runtime (the invoker won't touch another zone's device), so
 * the wizard never offers it.
 */
export function zoneActionOptions(
  zoneId: string,
  devices: readonly WorldDevice[],
  agents: readonly WorldAgent[],
): ZoneActionOption[] {
  const boundDeviceIds = new Set(agents.flatMap(agent => agent.boundDeviceIds));
  const byCapability = new Map<string, string[]>();
  for (const device of devices) {
    if (device.zoneId !== zoneId || !boundDeviceIds.has(device.id)) continue;
    for (const capability of device.capabilities) {
      const names = byCapability.get(capability);
      if (names) names.push(device.name);
      else byCapability.set(capability, [device.name]);
    }
  }
  return [...byCapability.entries()]
    .map(([capability, deviceNames]) => ({ capability, deviceNames }))
    .sort((a, b) => a.capability.localeCompare(b.capability));
}

export interface FlowWizardSelection {
  zoneId: string;
  parameter: string;
  op: WizardOp;
  threshold: number;
  capability: string;
  /** Display name (auto-generated by the wizard, user-editable). */
  name: string;
  /** Plan goal sentence (auto-generated alongside the name). */
  goal: string;
}

/** Step-1 gate: trigger fully specified (threshold must be a finite number). */
export function wizardTriggerReady(
  selection: Pick<FlowWizardSelection, 'zoneId' | 'parameter' | 'threshold'>,
): boolean {
  return (
    selection.zoneId !== '' &&
    selection.parameter !== '' &&
    Number.isFinite(selection.threshold)
  );
}

/**
 * Serialize the wizard selection into the create-flow body: a zone-scoped
 * condition trigger (false→true edge) plus one auto-assigned action node.
 * Carrying the trigger zoneId is what makes the engine actuate devices IN
 * that zone (R12 zone-blindness fix).
 */
export function buildFlowFromWizard(selection: FlowWizardSelection): CreateFlowInput {
  return {
    name: selection.name,
    description: '',
    enabled: true,
    trigger: {
      kind: 'condition',
      zoneId: selection.zoneId,
      conditions: [{ path: selection.parameter, op: selection.op, value: selection.threshold }],
    },
    plan: {
      goal: selection.goal,
      nodes: [{ id: 'n1', capability: selection.capability }],
    },
  };
}
